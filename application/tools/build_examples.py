"""Copy only allowlisted public-media results into the shareable application gallery."""
import json
import hashlib
from pathlib import Path
import shutil

from application.run import HOME, PROFILES, ROOT

EXTRAS = [
    ('video_route', '01_navigation_routiere/video', 'dashcam.mp4'),
    ('video_camera_laterale', '01_navigation_routiere/camera_inadaptee', 'camera-laterale.mp4'),
    ('industrie_allee', '05_industrie_passage/allee', 'warehouse.jpg'),
]


def copy_example(source, destination, public_input):
    reports = json.loads((source/'rapport.json').read_text(encoding='utf-8'))
    if not reports or any(report.get('source') != public_input for report in reports):
        raise ValueError('Publication refusee : les rapports ne referencent pas le media public attendu.')
    destination.mkdir(parents=True, exist_ok=True)
    selected = ['rapport.json', 'RAPPORT.md', 'index.html']
    if 'time_seconds' in reports[0]:
        selected += ['chronologie.csv', 'video_annotee.mp4', 'video_annotee.webm']
    selected += [f'vue_{i+1:03d}_comparaison.jpg' for i in range(len(reports))]
    # Depth arrays and personal inputs are never promoted automatically.
    for name in selected:
        original = source/name
        if original.is_file():
            shutil.copy2(original, destination/name)
    return reports


def main():
    manifest = json.loads((HOME/'assets'/'SOURCES.json').read_text(encoding='utf-8'))
    public = {record['file'] for record in manifest}
    for record in manifest:
        if hashlib.sha256((HOME/'assets'/record['file']).read_bytes()).hexdigest() != record['sha256']:
            raise ValueError('Media public modifie : verifier le manifeste avant de partager.')
    cards = []
    findings = []
    for app, profile in PROFILES.items():
        if profile['image'] not in public:
            raise ValueError('Source absente du manifeste')
        folder = profile['folder']
        reports = copy_example(ROOT/'results'/'application'/folder, HOME/folder/'exemples', profile['image'])
        report = reports[0]
        # Titles and actions are controlled, generated by our application, not user HTML.
        import html
        cards.append(f'<article><h2>{html.escape(profile["title"])}</h2>'
            f'<img src="{folder}/exemples/vue_001_comparaison.jpg" alt="Photo, profondeur et application">'
            f'<p><b>{report["status"]}</b> — {html.escape(report["action"])}</p>'
            f'<a href="{folder}/exemples/index.html">Ouvrir les resultats</a> · '
            f'<a href="{folder}/README.md">Explications et commandes</a></article>')
        findings.append({'application': app, 'status': report['status'], 'action': report['action'],
            'components': len(report.get('candidates', [])), 'source': report['source']})
    for source, target, public_input in EXTRAS:
        if public_input not in public:
            raise ValueError('Source absente du manifeste')
        reports = copy_example(ROOT/'results'/'application'/source, HOME/target, public_input)
        findings.append({'application': source, 'views': len(reports),
            'statuses': {state: sum(r['status'] == state for r in reports) for state in sorted({r['status'] for r in reports})},
            'temporal_statuses': {state: sum(r.get('temporal_status') == state for r in reports)
                for state in sorted({r['temporal_status'] for r in reports if 'temporal_status' in r})}})
    page = '<!doctype html><html lang="fr"><meta charset="utf-8"><meta name="viewport" content="width=device-width">'
    page += '<title>Applications de la profondeur monoculaire</title><style>body{font:17px system-ui;background:#111720;'
    page += 'color:#edf2fc;max-width:1200px;margin:32px auto;padding:16px}h1{font-size:36px}article{background:#1c2634;'
    page += 'border-radius:16px;padding:20px;margin:24px 0}img{width:100%;border-radius:8px}a{color:#8ecaff}'
    page += '.intro{color:#c0ccdf;max-width:850px}video{max-width:100%;border-radius:10px}</style>'
    page += '<h1>Une image, plusieurs applications</h1><p class="intro">Photos et videos reelles → profondeur estimee → '
    page += 'resultat visuel et action proposee. Cinq demonstrations sur CPU, avec les modeles deja installes, sans entrainement.</p>'
    page += '<p class="intro">Navigation : perception hors ligne et alertes simulees. Aucun vehicule ou robot pilote. '
    page += 'Les distances et la focale sont estimees ; aucun resultat ne garantit un passage libre.</p>'
    page += '<p><a href="README.md">Guide PowerShell</a> · <a href="docs/SOURCES.md">Sources et credits</a> · '
    page += '<a href="docs/BILAN.md">Resultats observes et prochaines etapes</a></p>'
    page += ''.join(cards)
    page += '<article><h2>Analyse d une vraie video routiere</h2><video controls muted playsinline '
    page += 'poster="01_navigation_routiere/video/vue_001_comparaison.jpg" '
    page += 'src="01_navigation_routiere/video/video_annotee.webm"></video>'
    page += '<p>Extrait analyse image par image. Vigilance et alertes a confirmer ; pas de suivi d objets ni de conduite autonome.</p>'
    page += '<a href="01_navigation_routiere/video/index.html">Les douze vues et leurs actions</a></article></html>'
    (HOME/'index.html').write_text(page, encoding='utf-8')
    (HOME/'docs'/'bilan.json').write_text(json.dumps(findings, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print('Galerie preparee : application/index.html')


if __name__ == '__main__':
    main()
